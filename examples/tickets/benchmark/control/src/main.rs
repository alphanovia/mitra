use std::path::Path;
use std::process::ExitCode;

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match tickets::run(&args, Path::new(tickets::LOG_FILE)) {
        Ok(out) => {
            if !out.is_empty() {
                println!("{out}");
            }
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("tickets: {e}");
            ExitCode::from(e.exit_code())
        }
    }
}
